package org.framedinterface.utils;

import java.io.File;
import java.io.IOException;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.nio.file.Files;
import java.time.Duration;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.framedinterface.model.DeclareModel;
import org.framedinterface.utils.enums.RecoveryStrategy;

/**
 * Turns an ENHSP plan (for a problem generated by the data-aware PDDL generator) into a replayable trace: one "action;activity" step per
 * plan event, as used by the models' updateMonitoringStates methods, plus the attribute values of each step.
 *
 * Plan actions are condensed as follows:
 *   validate-payload + sync-actions t<i> t<i+1> a                 -> "sync;<prefix event i>" (the prefix event replayed as is, with its own attribute values)
 *   skip-unused t<i> a t<i+1>                                    -> "skip;<prefix event i>" (a prefix event that no automaton knows)
 *   add_action a, add_parameter a p v..., check_added_parameter_model a, add_move_automata a
 *                                                                -> "add;<activity a>" (an event added by the planner, with attribute values p=v)
 *   reset c                                                      -> "reset constraint;<reset target of c>" (constraint c was violated and is reset)
 * Every step also gets a "timestamp" attribute: the plan's time (see HOURS_PER_PLAN_TIME_UNIT) added to the trace's start time; prefix events keep their own.
 *
 * The plan cost (the planner's metric times costFactor) is also split into its parts, which add up to it:
 *   activity cost  - the cost model's cost of each added activity (add_action), plus its cost per attribute value set on it (add_parameter)
 *   waiting cost   - the plan's "Elapsed Time" times costFactor (the metric charges one unit per unit of plan time)
 *   violation cost - Reset: the violation cost of each reset constraint (reset); No-Recovery: none; Skip: the plan cost minus the activity and
 *                    waiting cost. Not determinable from the plan for Discard (taken from the replay instead, see DataAwareController).
 */
public class EnhspPlanParser {

	public static final String SYNC_ACTION = "sync";
	public static final String SKIP_ACTION = "skip";
	public static final String ADD_ACTION = "add";

	private static final String TIMESTAMP_ATTRIBUTE = "timestamp";
	private static final DateTimeFormatter TIMESTAMP_FORMATTER = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss"); //Same format as the Data-Aware page's "timestamp" attribute
	private static final Pattern STEP_PATTERN = Pattern.compile("^\\s*(\\d+(?:\\.\\d+)?):\\s*\\((.*)\\)\\s*$"); //e.g. "19.0: (sync-actions t1 t2 a2)"; "-----waiting----" lines don't match
	private static final Pattern METRIC_PATTERN = Pattern.compile("^Metric \\(Search\\):\\s*(\\S+)");
	private static final Pattern ELAPSED_TIME_PATTERN = Pattern.compile("^Elapsed Time:\\s*(\\S+)");
	private static final Pattern COST_MODEL_LINE_PATTERN = Pattern.compile("^\\s*(.*?)\\s+(\\S+)\\s+(\\S+)\\s*$"); //"<ActivityName> <addCost> <setCost>"
	private static final Pattern VIOLATION_COST_LINE_PATTERN = Pattern.compile("^\\s*(.*?)\\s+(\\S+)\\s*$"); //"<model file>|<constraint name> <cost>" or "<model file> <cost>"
	private static final BigDecimal COST_MISMATCH_TOLERANCE = new BigDecimal("0.001");
	//The generator encodes event times in hours, but the domain's "waiting" process only advances them by 0.1 per unit of plan time, so plan time 20.0 = 2 hours
	private static final double HOURS_PER_PLAN_TIME_UNIT = 0.1;

	public static class ParsedPlan {
		private boolean solved;
		private String cost = "";
		private BigDecimal totalCost; //cost as a number; null if the metric isn't one
		private BigDecimal violationCost; //null if it can't be determined from the plan (Discard, or a metric that isn't a number)
		private BigDecimal activityCost = BigDecimal.ZERO;
		private BigDecimal waitingCost = BigDecimal.ZERO;
		private List<String> steps = new ArrayList<String>();
		private List<Map<String, String>> attributeValues = new ArrayList<Map<String, String>>(); //Parallel to steps
		private List<Integer> prefixEventSteps = new ArrayList<Integer>(); //Prefix event (0-based) -> the (1-based) step that replayed it, or -1

		public boolean isSolved() {
			return solved;
		}
		public String getCost() {
			return cost;
		}
		public BigDecimal getViolationCost() {
			return violationCost;
		}
		public BigDecimal getActivityCost() {
			return activityCost;
		}
		public BigDecimal getWaitingCost() {
			return waitingCost;
		}
		//Whether the given violation cost, activity cost and waiting cost add up to the plan cost. If they don't, the breakdown is off
		//(e.g. a cost that wasn't found under the name the plan uses, or a violation the replay judged differently than the planner)
		public boolean costPartsAddUp(BigDecimal violationCost) {
			return totalCost == null || totalCost.subtract(violationCost.add(activityCost).add(waitingCost)).abs().compareTo(COST_MISMATCH_TOLERANCE) <= 0;
		}
		public List<String> getSteps() {
			return steps;
		}
		public List<Map<String, String>> getAttributeValues() {
			return attributeValues;
		}
		public List<Integer> getPrefixEventSteps() {
			return prefixEventSteps;
		}
	}

	private Map<String, String> activityNames = new HashMap<String, String>(); //Activity encoding (e.g. "a10") -> activity name
	private Map<String, String> variableValues = new HashMap<String, String>(); //Value encoding (e.g. "integer550") -> value (e.g. "55")
	private Set<String> categoricalAttributes; //Lowercased; their value encodings are the categorical values themselves
	private Map<String, String> resetTargets; //Lowercased PDDL constraint name -> the activity a reset step should carry (default: the name itself)
	private BigDecimal costFactor; //The plan cost is the planner's metric times this
	private Map<String, BigDecimal> addCosts = new HashMap<String, BigDecimal>(); //Lowercased activity name -> cost of adding it
	private Map<String, BigDecimal> setCosts = new HashMap<String, BigDecimal>(); //Lowercased activity name -> cost of each attribute value set on an added event
	private Map<String, BigDecimal> violationCosts = new HashMap<String, BigDecimal>(); //Lowercased PDDL constraint name -> violation cost (hard constraints have none)
	private RecoveryStrategy recoveryStrategy; //Decides how a plan's violation cost is determined

	/**
	 * @param outputFolder the generator's output folder, holding its activity mapping files (activityMappingFilePattern)
	 * @param variableValuesFile the generator's value encodings (e.g. "integer550 55")
	 * @param costModelFile the cost model handed to the generator, one "<ActivityName> <addCost> <setCost>" line per activity
	 * @param violationCostFile the violation costs handed to the generator, "<model file>|<constraint name> <cost>" per Declare constraint and
	 *                          "<model file> <cost>" per Petri net ("x" for hard ones)
	 * @param categoricalAttributes lowercased names of categorical attributes, whose value encodings are used as is
	 * @param resetTargets lowercased PDDL constraint name -> activity for its reset steps (e.g. a Petri net's reset activity)
	 * @param costFactor the planner's metric is multiplied with it to get the plan cost (the generator scales costs relative to its default waiting cost)
	 * @param recoveryStrategy the strategy the plans were generated with, which decides how their violation cost is determined
	 */
	public EnhspPlanParser(File outputFolder, File variableValuesFile, String activityMappingFilePattern, File costModelFile, File violationCostFile,
			Set<String> categoricalAttributes, Map<String, String> resetTargets, BigDecimal costFactor, RecoveryStrategy recoveryStrategy) throws IOException {
		this.categoricalAttributes = categoricalAttributes;
		this.resetTargets = resetTargets;
		this.costFactor = costFactor;
		this.recoveryStrategy = recoveryStrategy;

		if (costModelFile.isFile()) {
			for (String line : readLines(costModelFile)) {
				Matcher matcher = COST_MODEL_LINE_PATTERN.matcher(line);
				if (matcher.matches()) {
					putCost(addCosts, matcher.group(1).toLowerCase(), matcher.group(2));
					putCost(setCosts, matcher.group(1).toLowerCase(), matcher.group(3));
				}
			}
		}

		if (violationCostFile.isFile()) {
			List<String> petriNetCosts = new ArrayList<String>(); //In file order, which is the order the generator numbers the nets in
			for (String line : readLines(violationCostFile)) {
				Matcher matcher = VIOLATION_COST_LINE_PATTERN.matcher(line);
				if (!matcher.matches()) {
					continue;
				}
				int modelSeparator = matcher.group(1).indexOf('|');
				if (modelSeparator >= 0) {
					putCost(violationCosts, matcher.group(1).substring(modelSeparator + 1).toLowerCase(), matcher.group(2));
				} else {
					petriNetCosts.add(matcher.group(2));
				}
			}
			//The generator's Petri net constraints: "pn" for a single net, otherwise "pn1", "pn2", ... (as in DataAwareController.assignPlannerConstraintNames)
			for (int i = 0; i < petriNetCosts.size(); i++) {
				putCost(violationCosts, petriNetCosts.size() == 1 ? "pn" : "pn" + (i + 1), petriNetCosts.get(i));
			}
		}

		File[] mappingFiles = outputFolder.listFiles((dir, name) -> name.matches(activityMappingFilePattern));
		if (mappingFiles != null) {
			for (File mappingFile : mappingFiles) {
				for (String line : readLines(mappingFile)) {
					int separator = line.lastIndexOf(':'); //e.g. "ActivityG:a10"
					if (separator > 0) {
						activityNames.putIfAbsent(line.substring(separator + 1).trim(), line.substring(0, separator).trim());
					}
				}
			}
		}

		if (variableValuesFile.isFile()) {
			for (String line : readLines(variableValuesFile)) {
				String[] parts = line.trim().split("\\s+"); //e.g. "integer550 55"
				if (parts.length == 2) {
					variableValues.put(parts[0], parts[1]);
				}
			}
		}
	}

	/**
	 * @param prefixEvents the prefix the plan was generated for (trace state t<i> is right before prefix event i)
	 * @param prefixAttributeValues the prefix's attribute values, keyed by (1-based) event number
	 * @param startTime the time the plan's time offsets are relative to (the prefix's first event, as exported)
	 */
	public ParsedPlan parse(File planFile, List<String> prefixEvents, Map<Integer, Map<String, String>> prefixAttributeValues, ZonedDateTime startTime) throws IOException {
		ParsedPlan plan = new ParsedPlan();
		for (int i = 0; i < prefixEvents.size(); i++) {
			plan.prefixEventSteps.add(-1);
		}

		boolean inPlan = false;
		String pendingAddActivity = null; //Set between add_action and add_move_automata
		Map<String, String> pendingAddValues = null;
		BigDecimal activityCost = BigDecimal.ZERO;
		BigDecimal violationCost = BigDecimal.ZERO;
		BigDecimal elapsedTime = BigDecimal.ZERO;

		for (String line : readLines(planFile)) {
			if (line.startsWith("Problem Solved")) {
				plan.solved = true;
			} else if (line.startsWith("Found Plan:")) {
				inPlan = true;
			} else if (inPlan && (line.isBlank() || line.startsWith("Plan-Length"))) {
				inPlan = false;
			} else if (inPlan) {
				Matcher stepMatcher = STEP_PATTERN.matcher(line);
				if (!stepMatcher.matches()) {
					continue;
				}
				double hours = Double.parseDouble(stepMatcher.group(1)) * HOURS_PER_PLAN_TIME_UNIT;
				String timestamp = startTime.plus(Duration.ofSeconds(Math.round(hours * 3600))).format(TIMESTAMP_FORMATTER);
				String[] action = stepMatcher.group(2).trim().split("\\s+");

				switch (action[0]) {
				case "sync-actions": //(sync-actions t<i> t<i+1> a)
				case "skip": //(skip-unused t<i> a t<i+1>)
					int prefixIndex = parseTraceState(action[1]);
					boolean isSync = action[0].equals("sync-actions");
					String activity = prefixIndex >= 0 && prefixIndex < prefixEvents.size() ? prefixEvents.get(prefixIndex) : decodeActivity(isSync ? action[3] : action[2]);
					Map<String, String> values = new LinkedHashMap<String, String>(prefixAttributeValues.getOrDefault(prefixIndex + 1, Collections.emptyMap()));
					values.putIfAbsent(TIMESTAMP_ATTRIBUTE, timestamp);
					addStep(plan, isSync ? SYNC_ACTION : SKIP_ACTION, activity, values);
					if (prefixIndex >= 0 && prefixIndex < prefixEvents.size()) {
						plan.prefixEventSteps.set(prefixIndex, plan.steps.size());
					}
					break;
				case "add_action": //(add_action a)
					pendingAddActivity = decodeActivity(action[1]);
					pendingAddValues = new LinkedHashMap<String, String>();
					activityCost = activityCost.add(lookUpCost(addCosts, pendingAddActivity, "activity"));
					break;
				case "add_parameter": //(add_parameter a p v)
					if (pendingAddValues != null && action.length >= 4) {
						pendingAddValues.put(action[2].toLowerCase(), decodeValue(action[2], action[3]));
					}
					activityCost = activityCost.add(lookUpCost(setCosts, decodeActivity(action[1]), "activity"));
					break;
				case "add_move_automata": //(add_move_automata a) - completes the added event
					if (pendingAddActivity != null) {
						pendingAddValues.put(TIMESTAMP_ATTRIBUTE, timestamp);
						addStep(plan, ADD_ACTION, pendingAddActivity, pendingAddValues);
						pendingAddActivity = null;
						pendingAddValues = null;
					}
					break;
				case "reset": //(reset c)
					Map<String, String> resetValues = new LinkedHashMap<String, String>();
					resetValues.put(TIMESTAMP_ATTRIBUTE, timestamp);
					addStep(plan, DeclareModel.RESET_CONSTRAINT_ACTION, resetTargets.getOrDefault(action[1].toLowerCase(), action[1]), resetValues);
					violationCost = violationCost.add(lookUpCost(violationCosts, action[1], "constraint"));
					break;
				default: //validate-payload, check_added_parameter_model and validate-failure carry no information needed for the replay
					break;
				}
			} else {
				Matcher elapsedTimeMatcher = ELAPSED_TIME_PATTERN.matcher(line);
				Matcher metricMatcher = METRIC_PATTERN.matcher(line);
				if (elapsedTimeMatcher.find()) { //Precedes the metric
					elapsedTime = parseNumber(elapsedTimeMatcher.group(1));
				} else if (metricMatcher.find()) {
					plan.cost = formatCost(metricMatcher.group(1));
					try {
						plan.totalCost = new BigDecimal(metricMatcher.group(1)).multiply(costFactor);
					} catch (NumberFormatException e) {
						//Left null, so the parts aren't checked against it
					}
					plan.activityCost = activityCost;
					plan.waitingCost = elapsedTime.multiply(costFactor);
					switch (recoveryStrategy) {
					case RESET:
					case NO_RECOVERY: //Allows no violations, and has no resets
						plan.violationCost = violationCost; //The plan's resets are all its violations
						break;
					case SKIP: //The plan doesn't show which events were skipped for which constraint, so the violation cost is whatever the other parts leave
						plan.violationCost = plan.totalCost == null ? null : plan.totalCost.subtract(plan.activityCost).subtract(plan.waitingCost);
						break;
					default: //Discard: taken from the replay (see DataAwareController)
						plan.violationCost = null;
						break;
					}
					break; //The metric follows the plan; only the first plan in the file is used (benchmark runs may append several)
				}
			}
		}
		return plan;
	}

	//Cost of the given activity / constraint (case-insensitive), or 0 if the cost files have none
	private static BigDecimal lookUpCost(Map<String, BigDecimal> costs, String name, String kind) {
		BigDecimal cost = costs.get(name.toLowerCase());
		if (cost == null) {
			System.out.println("EnhspPlanParser: no cost found for " + kind + " " + name + ", counted as 0");
			return BigDecimal.ZERO;
		}
		return cost;
	}

	private static void putCost(Map<String, BigDecimal> costs, String name, String cost) {
		try {
			costs.put(name, new BigDecimal(cost));
		} catch (NumberFormatException e) {
			//e.g. "x" for a hard constraint, which can't be violated
		}
	}

	//0 if not a number
	private static BigDecimal parseNumber(String number) {
		try {
			return new BigDecimal(number);
		} catch (NumberFormatException e) {
			return BigDecimal.ZERO;
		}
	}

	private static void addStep(ParsedPlan plan, String action, String activity, Map<String, String> attributeValues) {
		plan.steps.add(action + ";" + activity);
		plan.attributeValues.add(attributeValues);
	}

	private String decodeActivity(String encoding) {
		return activityNames.getOrDefault(encoding, encoding);
	}

	private String decodeValue(String attribute, String valueEncoding) {
		if (categoricalAttributes.contains(attribute.toLowerCase())) {
			return valueEncoding; //variable_values.txt holds an index for categorical values, the encoding is the value itself
		}
		return variableValues.getOrDefault(valueEncoding, valueEncoding);
	}

	//"t3" -> 3, or -1 if unparseable
	private static int parseTraceState(String traceState) {
		try {
			return Integer.parseInt(traceState.substring(1));
		} catch (RuntimeException e) {
			return -1;
		}
	}

	//"4061.0" -> "4061"
	//The metric times costFactor, without trailing zeros (e.g. "400" rather than "400.0"); a metric that isn't a number is shown as is
	private String formatCost(String metric) {
		try {
			return formatCost(new BigDecimal(metric).multiply(costFactor));
		} catch (NumberFormatException e) {
			return metric;
		}
	}

	//Rounded to 6 decimals, to hide the planner's floating-point noise (e.g. an elapsed time of 19.999999999)
	public static String formatCost(BigDecimal cost) {
		return cost.setScale(6, RoundingMode.HALF_UP).stripTrailingZeros().toPlainString();
	}

	private static List<String> readLines(File file) throws IOException {
		return List.of(new String(Files.readAllBytes(file.toPath())).split("\\R"));
	}
}
